// Writes the generated half of THIRD-PARTY.md: every crate from crates.io
// that is compiled into Slerp's programs, with its licence, and the text of
// each distinct licence once, preceded by the copyright lines of the crates
// that use it.  Most permissive licences (MIT, BSD, ISC, Zlib) ask that
// binary distributions carry the copyright notice and the licence, so the
// packages ship this file.
//
// Usage: deno run -A tools/third-party.ts           # rewrite THIRD-PARTY.md
//        deno run -A tools/third-party.ts --check   # exit 1 when it's stale
//
// The part of THIRD-PARTY.md above the marker line (material bundled in
// Slerp's own source) is written by hand and kept as it is.
//
// Crates are found with `cargo metadata` for the three platforms Slerp
// builds for, starting from the shipped programs (the `slerp` binary,
// Explorer's thumbnail handler and the Quick Look extension) and following
// normal dependencies only: build tools and test-only crates don't end up in
// what users get.  Licence files are read from each crate's source in
// Cargo's registry.  Where a crate offers MIT as one choice ("MIT OR
// Apache-2.0"), Slerp takes it under MIT and only its MIT text is listed.

const ROOT = new URL("..", import.meta.url).pathname.replace(/\/$/, "");
const OUTPUT = `${ROOT}/THIRD-PARTY.md`;
const MARKER = "<!-- Everything below this line is generated by tools/third-party.ts; edit above it. -->";
const PLATFORMS = ["x86_64-unknown-linux-gnu", "x86_64-pc-windows-gnu", "aarch64-apple-darwin"];
const SHIPPED = ["slerp", "slerp-winshell", "slerp-macos"];

/**
 * Notices of the third-party material in Slerp's own source, copied into the
 * file in full, since their licences ask binary distributions to carry them.
 * `from` and `to` cut a notice out of a source file's doc comment.
 */
const BUNDLED:{ title:string; path:string; from?:RegExp; to?:RegExp }[] = [
  { title: "openriglogic (Epic Games)", path: "crates/dna/openriglogic/LICENSE" },
  { title: "jxrlib (Microsoft)", path: "crates/jxr/vendor/jxrlib/LICENSE" },
  { title: "OpenSKP", path: "crates/sketchup/NOTICE" },
  {
    title: "LibreQuake and Freedoom palettes",
    path: "crates/quake/src/pixels.rs",
    from: /^Copyright \(c\) 2019/,
    to: /SUCH DAMAGE\.$/,
  },
  { title: "Lucide and Feather icons", path: "crates/theme/icons/LICENSE" },
  { title: "Unscii font", path: "crates/retro/font/NOTICE" },
];

/** Licence files some crates keep under names no pattern would guess. */
const EXTRA_FILES:Record<string, string[]> = {
  epaint_default_fonts: ["fonts/Hack-Regular.txt"],
};

/** Folders inside a crate whose licence files describe things that don't ship. */
const SKIP_DIRS = new Set([
  "target", "tests", "test", "testdata", "test-data", "benches", "examples", "fuzz", ".github", "ci", "scripts",
]);

//#region Reading the crates

interface Package {
  id:string;
  name:string;
  version:string;
  license:string|null;
  license_file:string|null;
  manifest_path:string;
  source:string|null;
  repository:string|null;
  authors:string[];
}

interface Node {
  id:string;
  deps:{ pkg:string; dep_kinds:{ kind:string|null; target:string|null }[] }[];
}

/** The crates.io packages reachable from the shipped programs through normal dependencies. */
async function shippedCrates():Promise<Package[]> {
  const args = ["metadata", "--format-version", "1", "--locked", ...PLATFORMS.flatMap(p => ["--filter-platform", p])];
  const out = await new Deno.Command("cargo", { args, cwd: ROOT, stdout: "piped", stderr: "inherit" }).output();
  if (!out.success) throw new Error("cargo metadata failed");
  const meta = JSON.parse(new TextDecoder().decode(out.stdout));
  const packages = new Map<string, Package>(meta.packages.map((p:Package) => [p.id, p]));
  const nodes = new Map<string, Node>(meta.resolve.nodes.map((n:Node) => [n.id, n]));

  const seen = new Set<string>();
  const stack = [...packages.values()].filter(p => p.source === null && SHIPPED.includes(p.name)).map(p => p.id);
  while (stack.length) {
    const id = stack.pop()!;
    if (seen.has(id)) continue;
    seen.add(id);
    for (const dep of nodes.get(id)?.deps ?? [])
      if (dep.dep_kinds.some(k => k.kind === null)) stack.push(dep.pkg);
  }
  return [...seen].map(id => packages.get(id)!).filter(p => p.source !== null)
    .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version, undefined, { numeric: true }));
}

/** Paths, relative to the crate's folder, of the files that look like licences or notices. */
async function licenceFiles(dir:string, rel = "", depth = 0):Promise<string[]> {
  const found:string[] = [];
  let entries:Deno.DirEntry[];
  try {
    entries = [...Deno.readDirSync(`${dir}/${rel}`)];
  } catch {
    return found;
  }
  for (const e of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    const path = rel ? `${rel}/${e.name}` : e.name;
    if (e.isDirectory) {
      if (depth < 3 && !SKIP_DIRS.has(e.name.toLowerCase())) found.push(...await licenceFiles(dir, path, depth + 1));
    } else if (/licen[cs]e|copying|notice|copyright|^unlicense|^ofl\.txt$|^ufl\.txt$/i.test(e.name)
      && !/\.(rs|toml|json|html?|c|h|cc|cpp|py|sh|yml|yaml|in|cmake)$/i.test(e.name)) {
      found.push(path);
    }
  }
  return found;
}

//#endregion

//#region Recognising licence texts

type Kind = "MIT" | "Apache-2.0" | "BSD" | "ISC" | "Zlib" | "Unlicense" | "CC0-1.0" | "BSL-1.0" | "MPL-2.0"
  | "GPL" | "OFL-1.1" | "UFL-1.0" | "Unicode" | "other";

function kindOf(text:string):Kind {
  const t = text.replace(/\s+/g, " ");
  // MPL's text names the GPL family as secondary licences, so it is checked first.
  if (/Mozilla Public License,? (Version|v\.) 2\.0/i.test(t)) return "MPL-2.0";
  if (/GNU (LESSER |LIBRARY )?GENERAL PUBLIC LICENSE/i.test(t)) return "GPL";
  if (/Apache License,? Version 2\.0/i.test(t) && /TERMS AND CONDITIONS/i.test(t)) return "Apache-2.0";
  if (/Permission is hereby granted, free of charge, to any person obtaining a copy of this software/i.test(t))
    return "MIT";
  if (/Redistribution and use in source and binary forms/i.test(t)) return "BSD";
  if (/Permission to use, copy, modify, and\/?or distribute this software for any purpose/i.test(t)) return "ISC";
  if (/This software is provided 'as-is', without any express or implied warranty/i.test(t)) return "Zlib";
  if (/This is free and unencumbered software released into the public domain/i.test(t)) return "Unlicense";
  if (/CC0 1\.0 Universal|Creative Commons Legal Code\s+CC0/i.test(t)) return "CC0-1.0";
  if (/Boost Software License/i.test(t)) return "BSL-1.0";
  if (/SIL OPEN FONT LICENSE/i.test(t)) return "OFL-1.1";
  if (/UBUNTU FONT LICEN[CS]E/i.test(t)) return "UFL-1.0";
  if (/UNICODE LICENSE|Unicode, Inc\./i.test(t) && /Permission is hereby granted/i.test(t)) return "Unicode";
  return "other";
}

/** Licences a crate may offer as alternatives to MIT, which Slerp then doesn't use. */
const ALTERNATIVES = new Set<Kind>(["Apache-2.0", "Unlicense", "BSL-1.0", "Zlib", "CC0-1.0", "GPL"]);

/** Whether `expr` lets Slerp take the crate under MIT instead of `kind`. */
function mitInstead(expr:string, kind:Kind):boolean {
  if (!/\bMIT\b/.test(expr) || !/\bOR\b|\//.test(expr)) return false;
  return ALTERNATIVES.has(kind);
}

/** Splits a licence into its copyright lines and the rest, which is the same for every user of the licence. */
function split(text:string):{ copyright:string[]; body:string } {
  const copyright:string[] = [];
  const body:string[] = [];
  for (const line of text.replace(/\r\n?/g, "\n").split("\n")) {
    // Licences copied out of source files keep their comment markers.
    const t = line.trim().replace(/^(\/\/+|#+|\*+|;+)\s*/, "");
    // A notice starts with a capital: lines of prose that wrap onto "copyright" don't.
    const notice = /^(Copyright|COPYRIGHT)\b(?!\s*:?\s*$)(?!\s+(holder|notice|owner|and|statement|law|licen[cs]e)s?\b)/i
      .test(t) && /^C/.test(t) || /^(\(c\)|©)\s*\d/i.test(t);
    if (notice && !/\[yyyy\]|\{yyyy\}|<year>|\[name of copyright owner\]/i.test(t))
      copyright.push(t.replace(/\s+/g, " "));
    else body.push(line.replace(/\s+$/, ""));
  }
  while (body.length && !body[0].trim()) body.shift();
  while (body.length && !body.at(-1)!.trim()) body.pop();
  return { copyright, body: body.join("\n") };
}

/** The key that makes two copies of one licence the same: words only, without titles or Apache's appendix. */
function keyOf(kind:Kind, body:string):string {
  let t = body;
  if (kind === "Apache-2.0") t = t.replace(/END OF TERMS AND CONDITIONS[\s\S]*$/i, "");
  if (kind === "MIT") t = t.replace(/^\s*(the\s+)?mit\s+licen[cs]e(\s*\(mit\))?\s*/i, "");
  return kind + ":" + t.toLowerCase().replace(/[“”"'`‘’]/g, "").replace(/[^a-z0-9]+/g, " ").trim();
}

