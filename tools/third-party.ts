/**
 * The standard text of a crate's licence, for crates published without a
 * licence file: MIT with the crate's authors as the copyright holders, else
 * Apache-2.0.  Public-domain dedications (CC0, the Unlicense) need no notice.
 */
function fallback(c:Package):{ file:string; text:string; kind:Kind }[] {
  const expr = c.license ?? "";
  const holders = c.authors.length ? c.authors.map(a => a.replace(/\s*<[^>]*>/, "")).join(", ") : `the ${c.name} authors`;
  if (/\bMIT\b/.test(expr)) {
    const mit = Deno.readTextFileSync(`${ROOT}/LICENSE-MIT`).replace(/^Copyright .*$/m, `Copyright (c) ${holders}`);
    return [{ file: "(standard text; the crate ships none)", text: mit, kind: "MIT" }];
  }
  if (/\bBSD-3-Clause\b/.test(expr)) return [{ file: "(standard text; the crate ships none)", text: BSD3(holders), kind: "BSD" }];
  if (/\bApache-2\.0\b/.test(expr)) {
    const apache = Deno.readTextFileSync(`${ROOT}/LICENSE-APACHE`);
    return [{ file: "(standard text; the crate ships none)", text: apache, kind: "Apache-2.0" }];
  }
  return [];
}

/** `text` as a Markdown code block, fenced with more backticks than it holds in a row. */
function fenced(text:string):string[] {
  const longest = Math.max(2, ...(text.match(/`+/g) ?? []).map(m => m.length));
  const fence = "`".repeat(longest + 1);
  return [fence + "text", text, fence];
}

/** The full notices of the bundled material, from the files that hold them. */
function bundledNotices():string[] {
  const out = ["## Notices of the bundled material", ""];
  for (const b of BUNDLED) {
    let lines = Deno.readTextFileSync(`${ROOT}/${b.path}`).replace(/\r\n?/g, "\n").split("\n");
    if (b.path.endsWith(".rs")) lines = lines.filter(l => l.startsWith("//!")).map(l => l.replace(/^\/\/! ?/, ""));
    if (b.from) lines = lines.slice(lines.findIndex(l => b.from!.test(l)));
    if (b.to) lines = lines.slice(0, lines.findIndex(l => b.to!.test(l)) + 1);
    if (!lines.length || !lines.join("").trim()) throw new Error(`no notice found in ${b.path}`);
    out.push(`### ${b.title}`, "", `From \`${b.path}\`.`, "", ...fenced(lines.join("\n")), "");
  }
  return out;
}

interface Text { kind:Kind; key:string; body:string; users:{ crate:string; file:string; copyright:string[] }[] }

const PERMISSIVE = /^(MIT|Apache-2\.0|BSD-[23]-Clause|ISC|Zlib|Unlicense|CC0-1\.0|BSL-1\.0|0BSD|Unicode-3\.0|Unicode-DFS-2016|OFL-1\.1|Ubuntu-font-1\.0|MIT-0|LLVM-exception|Apache-2\.0 WITH LLVM-exception|bzip2-1\.0\.6|CDLA-Permissive-2\.0)$/;

async function generate():Promise<string> {
  const crates = await shippedCrates();
  const texts = new Map<string, Text>();
  const warnings:string[] = [];
  const rows:string[] = [];

  for (const c of crates) {
    const dir = c.manifest_path.replace(/\/Cargo\.toml$/, "");
    const expr = c.license ?? (c.license_file ? `see ${c.license_file}` : "none given");
    const files = [...new Set([...await licenceFiles(dir), ...(EXTRA_FILES[c.name] ?? [])])];
    const read = files.map(f => ({ file: f, text: Deno.readTextFileSync(`${dir}/${f}`) }))
      .map(r => ({ ...r, kind: kindOf(r.text) }));
    const hasMit = read.some(r => r.kind === "MIT" && !r.file.includes("/"));
    let kept = read.filter(r => !(hasMit && mitInstead(expr, r.kind)) && r.text.trim().length > 0);
    // A GPL-family text beside a permissive one is the other half of a choice (zstd is BSD or GPLv2).
    const folder = (f:string) => f.replace(/[^/]*$/, "");
    kept = kept.filter(r => r.kind !== "GPL" || !kept.some(o => o.kind !== "GPL" && o.kind !== "other"
      && folder(o.file) === folder(r.file)));
    if (kept.length === 0) kept = fallback(c);

    for (const r of read.filter(r => r.kind === "GPL"))
      if (kept.includes(r)) warnings.push(`${c.name} ${c.version}: ${r.file} is a GPL-family text (${expr})`);
    if (!c.license) warnings.push(`${c.name} ${c.version}: no SPDX licence in Cargo.toml (${expr})`);
    else for (const part of c.license.replace(/[()]/g, " ").split(/\s+(?:AND|OR|WITH)\s+|\//))
      if (part.trim() && !PERMISSIVE.test(part.trim()) && !/\bOR\b|\//.test(c.license))
        warnings.push(`${c.name} ${c.version}: licence ${c.license} is not on the permissive list`);
    // Public-domain dedications and the Boost licence ask for no notice in compiled programs.
    if (kept.length === 0 && !/^(CC0-1\.0|Unlicense|BSL-1\.0)$/.test(expr))
      warnings.push(`${c.name} ${c.version}: no licence text found or known (${expr})`);

    for (const r of kept) {
      const { copyright, body } = split(r.text);
      const key = keyOf(r.kind, body);
      const entry = texts.get(key) ?? { kind: r.kind, key, body, users: [] };
      entry.users.push({ crate: `${c.name} ${c.version}`, file: r.file, copyright });
      texts.set(key, entry);
    }
    const link = c.repository ? `[${c.name}](${c.repository.replace(/\.git$/, "")})` : c.name;
    rows.push(`| ${link} | ${c.version} | ${expr.replace(/\|/g, "\\|")} |`);
  }

  // Most-used licence texts first, then by kind.
  const order = [...texts.values()].sort((a, b) => b.users.length - a.users.length || a.kind.localeCompare(b.kind));
  const out:string[] = bundledNotices();
  out.push("## Rust crates", "");
  out.push(`These ${crates.length} crates from crates.io are compiled into Slerp's programs: the \`slerp\` program on Linux, Windows and macOS, Explorer's thumbnail handler and the Quick Look extension.  Where a crate offers a choice that includes MIT, Slerp uses it under MIT.  The licence texts follow the table.`, "");
  out.push("| Crate | Version | Licence |", "|---|---|---|", ...rows, "");
  out.push("## Licence texts", "");
  out.push("Each licence text appears once, after the copyright notices of the crates that use it.", "");
  const kindsSeen = new Set<Kind>();
  for (const t of order) {
    const names = t.users.map(u => u.crate);
    out.push(`### ${title(t, kindsSeen.has(t.kind))}`, "");
    kindsSeen.add(t.kind);
    out.push(`Used by ${names.length === 1 ? names[0] : `${names.length} crates`}.`, "");
    const notices = t.users.flatMap(u => u.copyright.length
      ? [`- ${u.crate}${u.file.includes("/") ? ` (\`${u.file}\`)` : ""}: ${u.copyright.join("; ")}`]
      : t.users.length > 1 ? [`- ${u.crate}`] : []);
    if (notices.length) out.push(...notices, "");
    out.push(...fenced(t.body), "");
  }
  for (const w of warnings) console.error("warning: " + w);
  return out.join("\n");
}

/**
 * A heading for a licence text: its kind, and for texts other than the most
 * common wording of MIT and Apache-2.0, the first crate that uses it.
 */
function title(t:Text, again:boolean):string {
  const names:Record<Kind, string> = {
    "MIT": "MIT License", "Apache-2.0": "Apache License 2.0", "BSD": "BSD licence", "ISC": "ISC License",
    "Zlib": "zlib License", "Unlicense": "The Unlicense", "CC0-1.0": "CC0 1.0", "BSL-1.0": "Boost Software License 1.0",
    "MPL-2.0": "Mozilla Public License 2.0", "GPL": "GPL-family licence", "OFL-1.1": "SIL Open Font License 1.1",
    "UFL-1.0": "Ubuntu Font Licence 1.0", "Unicode": "Unicode licence", "other": "Other terms",
  };
  const first = `${t.users[0].crate}${t.users.length > 1 ? " and others" : ""}`;
  if (t.kind === "MIT" || t.kind === "Apache-2.0") return again ? `${names[t.kind]}, as worded by ${first}` : names[t.kind];
  return `${names[t.kind]}: ${first}`;
}

//#endregion

const generated = await generate();
const current = await Deno.readTextFile(OUTPUT).catch(() => "");
const at = current.indexOf(MARKER);
if (at < 0) {
  console.error(`${OUTPUT} has no marker line; add this line where the generated part starts:\n${MARKER}`);
  Deno.exit(2);
}
const next = current.slice(0, at + MARKER.length) + "\n\n" + generated;
if (Deno.args.includes("--check")) {
  if (next !== current) {
    console.error("THIRD-PARTY.md is out of date: run deno run -A tools/third-party.ts");
    Deno.exit(1);
  }
} else if (next !== current) {
  await Deno.writeTextFile(OUTPUT, next);
  console.log(`Wrote ${OUTPUT} (${(next.length / 1024).toFixed(0)} KB)`);
} else {
  console.log("THIRD-PARTY.md is up to date");
}
