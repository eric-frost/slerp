//! Image data-blocks: the pixels a material's image textures use, packed
//! into the `.blend` file or in files beside it.
//!
//! Blender stores an image's path as the user picked it: relative to the
//! `.blend` file when it starts with `//`, otherwise absolute, often from
//! another machine.  Files that moved with their textures are found by
//! trying the stored path, then the file name beside the `.blend` file and
//! in a `textures` folder there.  Pixels decode through the textures crate,
//! except OpenEXR, which Blender users favour for data maps and which the
//! shared `slerp-openexr` crate decodes.

use crate::view::Obj;
use slerp_scene::textures::{ColorSpace, DecodeOptions, Format, Original, Pixels, Texture};
use slerp_scene::{Limits, record_neighbour};
use std::path::{Path, PathBuf};

/// The largest EXR accepted, in texels: 16K square.
const MAX_EXR_TEXELS: usize = 16384 * 16384;

/// Decodes image data-block `im`.  `Err` carries a message for the
/// loader's warnings.
pub fn load(im: &Obj, dir: Option<&Path>, limits: &Limits) -> Result<Texture, String> {
    let name = im.id_name();
    let source = im.int(&["source"]).unwrap_or(1);
    match source {
        4 => return Err(format!("image \"{name}\" is generated by Blender")),
        2 | 3 | 5 => return Err(format!("image \"{name}\" is a movie, sequence or viewer")),
        _ => {}
    }
    let path = im.string("name");
    let path = if path.is_empty() { im.string("filepath") } else { path };
    let path = path.replace("<UDIM>", "1001").replace("<UVTILE>", "u1_v1");
    let opts = match limits.max_texture_size {
        Some(n) => DecodeOptions::preview(n),
        None => DecodeOptions::full(),
    };
    // Saving a picture unchanged (a GLB export) needs its encoded bytes:
    // a copy for packed ones, the file for the rest.
    let file_name = path.replace('\\', "/").rsplit('/').next().filter(|n| !n.is_empty()).unwrap_or(&name).to_string();
    let with_source = |mut t: Texture, original: Option<Original>| {
        t.source.name = file_name.clone();
        t.source.original = original;
        t
    };
    // 1. Packed into the file.
    if let Some(bytes) = packed(im) {
        let original = limits.originals.then(|| Original::Memory(bytes.into()));
        return decode(bytes, &path, &opts, limits)
            .map(|t| with_source(t, original))
            .map_err(|e| format!("packed image \"{name}\": {e}"));
    }
    // 2. Beside it.
    if !limits.neighbours {
        return Err(format!("image \"{name}\" is a separate file"));
    }
    let candidates = candidates(&path, dir);
    for p in &candidates {
        record_neighbour(p);
        if let Ok(bytes) = std::fs::read(p) {
            let original = Original::File { path: p.clone(), offset: 0, len: bytes.len() as u64 };
            return decode(&bytes, &path, &opts, limits)
                .map(|t| with_source(t, Some(original)))
                .map_err(|e| format!("image {}: {e}", p.display()));
        }
    }
    Err(format!("image file not found: {path}"))
}

/// The packed bytes of an image: Blender 2.8 and later keep a list of packed
/// files (one per view and UDIM tile), older versions one packed file.
fn packed<'a>(im: &Obj<'a>) -> Option<&'a [u8]> {
    let pf = im
        .list("packedfiles")
        .into_iter()
        .find_map(|ipf| ipf.deref("packedfile"))
        .or_else(|| im.deref("packedfile"))?;
    let size = pf.int(&["size"])?.max(0) as usize;
    let data = pf.raw("data")?;
    data.get(..size)
}

/// Where an image's file may be: its stored path (relative to the
/// `.blend` file's folder when it starts with `//`), then its file name
/// beside the `.blend` file and in a `textures` folder there.
fn candidates(stored: &str, dir: Option<&Path>) -> Vec<PathBuf> {
    let mut out = Vec::new();
    let unified = stored.replace('\\', "/");
    if let Some(rel) = unified.strip_prefix("//") {
        if let Some(d) = dir {
            out.push(d.join(rel));
        }
    } else if !unified.is_empty() {
        out.push(PathBuf::from(&unified));
    }
    if let (Some(d), Some(file)) = (dir, unified.rsplit('/').next().filter(|n| !n.is_empty())) {
        for p in [d.join(file), d.join("textures").join(file), d.join("Textures").join(file)] {
            if !out.contains(&p) {
                out.push(p);
            }
        }
    }
    out
}

fn decode(bytes: &[u8], path: &str, opts: &DecodeOptions, limits: &Limits) -> Result<Texture, String> {
    if bytes.starts_with(&[0x76, 0x2f, 0x31, 0x01]) {
        return decode_exr(bytes, limits.max_texture_size);
    }
    let ext = path.rsplit('.').next().unwrap_or("").to_ascii_lowercase();
    let result = if slerp_scene::textures::sniff(bytes).is_some() {
        slerp_scene::textures::decode(bytes, opts)
    } else if ext == "tga" {
        slerp_scene::textures::decode_as(Format::Tga, bytes, opts)
    } else {
        return Err(format!("unsupported image format (.{ext})"));
    };
    result.map_err(|e| e.to_string())
}

/// Decodes an OpenEXR image to linear float RGBA through the shared
/// OpenEXR crate (its first colour layer, or luminance as grey), shrunk to
/// `max` if given.
fn decode_exr(bytes: &[u8], max: Option<u32>) -> Result<Texture, String> {
    let p = slerp_openexr::decode_default(bytes, max, MAX_EXR_TEXELS as u64)?;
    let l = p.levels.into_iter().next().ok_or("EXR without pixels")?;
    let mut tex = Texture::from_rgba32f(l.width, l.height, l.rgba);
    tex.color_space = ColorSpace::Linear;
    tex.source.container = "OpenEXR".into();
    Ok(tex)
}

/// Channel `c` (0 red to 3 alpha, 4 for luminance) of texel (x, y) of a
/// texture's first level, as 0 to 1.
pub fn sample(tex: &Texture, x: u32, y: u32, c: usize) -> f32 {
    let l = &tex.levels[0];
    let (x, y) = (x.min(l.width.saturating_sub(1)), y.min(l.height.saturating_sub(1)));
    let i = (y as usize * l.width as usize + x as usize) * 4;
    let get = |k: usize| match l.surfaces.first() {
        Some(Pixels::Rgba8(p)) => p.get(i + k).map_or(0.0, |&v| v as f32 / 255.0),
        Some(Pixels::Rgba32F(p)) => p.get(i + k).copied().unwrap_or(0.0),
        _ => 0.0,
    };
    if c == 4 { 0.2126 * get(0) + 0.7152 * get(1) + 0.0722 * get(2) } else { get(c.min(3)) }
}
