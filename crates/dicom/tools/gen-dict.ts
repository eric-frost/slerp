/**
 * Writes `crates/dicom/src/dict_data.rs`: the DICOM data dictionary (tag, value representation and name of every
 * standard attribute, plus the repeating groups such as overlays) and the names of the standard UIDs (transfer
 * syntaxes, SOP classes).  The source is pydicom's generated dictionaries (MIT), pinned to one commit so the output
 * only changes when the pin does; pydicom builds them from the DICOM standard's own XML.
 *
 * Usage: `deno run --allow-net --allow-write crates/dicom/tools/gen-dict.ts`
 *
 * Names are packed into one string with offsets, so the table needs no relocations and stays about 200 KB.
 */

const COMMIT = '60cebd027861e0dd4dfac12431679cb49e0156c3'
const BASE = `https://raw.githubusercontent.com/pydicom/pydicom/${COMMIT}/src/pydicom`
const OUT = new URL('../src/dict_data.rs', import.meta.url)

/** One attribute: its tag (with `x` digits as 0 for repeaters), the mask of fixed digits, VR and name. */
interface Attribute {
	tag:number
	mask:number
	vr:string
	name:string
}

async function fetchText(url:string):Promise<string> {
	const res = await fetch(url)
	if (!res.ok)
		throw new Error(`${url}: ${res.status}`)
	return await res.text()
}

/** The first VR of an ambiguous one ("US or SS" becomes "US"), and "NONE" (item tags) as two spaces. */
function vrCode(vr:string):string {
	const first = vr.split(' or ')[0]
	return first === 'NONE' ? '  ' : first
}

function parseAttributes(py:string):Attribute[] {
	const out:Attribute[] = []
	const fixed = /^\s+0x([0-9A-F]{8}): \('([^']*)', '[^']*', "([^"]*)", '[^']*', '[^']*'\),?$/
	const repeat = /^\s+'([0-9A-Fx]{8})': \('([^']*)', '[^']*', "([^"]*)", '[^']*', '[^']*'\),?$/
	for (const line of py.split('\n')) {
		let m = fixed.exec(line)
		if (m) {
			out.push({tag: parseInt(m[1], 16), mask: 0xFFFFFFFF, vr: vrCode(m[2]), name: m[3]})
			continue
		}
		m = repeat.exec(line)
		if (m) {
			const digits = m[1]
			const tag = parseInt(digits.replaceAll('x', '0'), 16)
			const mask = parseInt([...digits].map(c => c === 'x' ? '0' : 'F').join(''), 16)
			out.push({tag, mask, vr: vrCode(m[2]), name: m[3]})
		}
	}
	return out
}

function parseUids(py:string):[string, string][] {
	const out:[string, string][] = []
	const re = /^\s+'([0-9.]+)': \('([^']*)', '[^']*', '[^']*', '[^']*', '[^']*'\),?$/
	for (const line of py.split('\n')) {
		const m = re.exec(line)
		if (m)
			out.push([m[1], m[2]])
	}
	return out
}

/** Packs names into one string and returns each name's `offset << 8 | length`. */
class Packer {
	text = ''
	seen = new Map<string, number>()
	add(s:string):number {
		const bytes = new TextEncoder().encode(s).length
		if (bytes > 255)
			throw new Error(`name too long: ${s}`)
		let at = this.seen.get(s)
		if (at === undefined) {
			at = new TextEncoder().encode(this.text).length
			this.text += s
			this.seen.set(s, at)
		}
		return at * 256 + bytes
	}
}

function rustString(s:string):string {
	return JSON.stringify(s)
}

const hex = (n:number) => '0x' + n.toString(16).toUpperCase().padStart(8, '0')

const attrs = parseAttributes(await fetchText(`${BASE}/_dicom_dict.py`))
const uids = parseUids(await fetchText(`${BASE}/_uid_dict.py`))
const fixed = attrs.filter(a => a.mask === 0xFFFFFFFF).sort((a, b) => a.tag - b.tag)
const repeaters = attrs.filter(a => a.mask !== 0xFFFFFFFF)
uids.sort((a, b) => a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0)
const names = new Packer()
const uidText = new Packer()

let rs = `// Generated by crates/dicom/tools/gen-dict.ts from pydicom ${COMMIT} (MIT), which builds its
// dictionaries from the DICOM standard.  Do not edit.

/// Standard attributes sorted by tag: (tag, VR, name as \`offset << 8 | length\` in [\`NAMES\`]).
pub(crate) static TAGS: &[(u32, [u8; 2], u32)] = &[\n`
for (const a of fixed)
	rs += `    (${hex(a.tag)}, *b"${a.vr}", ${names.add(a.name)}),\n`
rs += `];

/// Attributes of repeating groups (overlays 60xx, curves 50xx and a few retired ones): (tag with the
/// repeating digits 0, mask of the fixed digits, VR, name).
pub(crate) static REPEATERS: &[(u32, u32, [u8; 2], u32)] = &[\n`
for (const a of repeaters)
	rs += `    (${hex(a.tag)}, ${hex(a.mask)}, *b"${a.vr}", ${names.add(a.name)}),\n`
rs += `];

/// Standard UIDs sorted as text: (UID, name as \`offset << 8 | length\` in [\`UID_NAMES\`]).
pub(crate) static UIDS: &[(&str, u32)] = &[\n`
for (const [uid, name] of uids)
	rs += `    (${rustString(uid)}, ${uidText.add(name)}),\n`
rs += `];

pub(crate) static NAMES: &str = ${rustString(names.text)};

pub(crate) static UID_NAMES: &str = ${rustString(uidText.text)};
`
await Deno.writeTextFile(OUT, rs)
console.log(`${fixed.length} attributes, ${repeaters.length} repeaters, ${uids.length} UIDs`)
