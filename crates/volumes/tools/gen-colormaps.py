#!/usr/bin/env python3
"""Writes src/colormap_data.rs: 64 stops of each colour map the viewer offers,
sampled from matplotlib (pip install matplotlib).  Run from the crate folder:

    python3 tools/gen-colormaps.py > src/colormap_data.rs
"""
from matplotlib import colormaps

MAPS = [("Viridis", "viridis"), ("Inferno", "inferno"), ("Magma", "magma"), ("Plasma", "plasma"),
        ("Cividis", "cividis"), ("Turbo", "turbo"), ("Hot", "hot"), ("Coolwarm", "coolwarm"), ("Jet", "jet")]

print("""//! Colour map tables: 64 evenly spaced stops each, sampled from matplotlib's maps
//! (Viridis, Inferno, Magma, Plasma and Cividis are CC0; Turbo is Apache-2.0
//! (Google); Hot, Coolwarm and Jet are matplotlib's own formula-based maps).
//! Generated by `tools/gen-colormaps.py`; do not edit by hand.
""")
for label, name in MAPS:
    cm = colormaps[name]
    rows = []
    for i in range(64):
        r, g, b, _ = cm(i / 63)
        rows.append("[%d, %d, %d]" % (round(r * 255), round(g * 255), round(b * 255)))
    body = "\n".join("    " + ", ".join(rows[k:k + 6]) + "," for k in range(0, 64, 6))
    print("pub const %s: [[u8; 3]; 64] = [\n%s\n];\n" % (label.upper(), body))
