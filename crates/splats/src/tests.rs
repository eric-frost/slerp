fn corpus(name: &str) -> Option<std::path::PathBuf> {
    let p = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../local/assets/splats").join(name);
    p.exists().then_some(p)
}

/// The public captures `tools/fetch-test-assets.ts` downloads: format,
/// splat count and spherical-harmonic degree as their headers say.
#[test]
fn reads_public_captures() {
    let cases = [
        ("point_cloud.ply", SplatFormat::Ply, 109_278, 3),
        ("luigi.ply", SplatFormat::Ply, 14_526, 0),
        ("plush.splat", SplatFormat::Splat, 281_498, 0),
        ("hornedlizard.spz", SplatFormat::Spz, 786_233, 3),
        ("guitar.compressed.ply", SplatFormat::CompressedPly, 90_854, 0),
    ];
    for (name, format, count, degree) in cases {
        let Some(path) = corpus(name) else {
            eprintln!("skipped {name}: not downloaded");
            continue;
        };
        let head: Vec<u8> = std::fs::read(&path).unwrap().into_iter().take(4096).collect();
        assert_eq!(sniff(&path, &head), Some(format), "{name}");
        let scene = load(format, &path, &Limits::viewer()).unwrap();
        let s = splats_of(&scene);
        assert_eq!(s.len(), count, "{name}");
        assert_eq!(s.sh_degree, degree, "{name}");
        assert!(s.positions.iter().all(|p| p.is_finite()), "{name}");
        let dense = s.dense_bounds();
        assert!(!dense.is_empty() && dense.size().max_element() < 1000.0, "{name}: {dense:?}");
        // Most splats of a capture are at least partly opaque.
        let visible = s.colors.iter().filter(|c| c.w > 0.1).count();
        assert!(visible * 2 > s.len(), "{name}: {visible} of {} visible", s.len());
    }
    if let Some(path) = corpus("apartment.sog") {
        let head: Vec<u8> = std::fs::read(&path).unwrap().into_iter().take(4096).collect();
        assert_eq!(sniff(&path, &head), Some(SplatFormat::Sog));
        let scene = load(SplatFormat::Sog, &path, &Limits::viewer()).unwrap();
        let s = splats_of(&scene);
        assert_eq!(s.len(), 661_466);
        assert!(s.positions.iter().all(|p| p.is_finite()));
        let visible = s.colors.iter().filter(|c| c.w > 0.1).count();
        assert!(visible * 2 > s.len(), "{visible} of {} visible", s.len());
        let thin = load(SplatFormat::Sog, &path, &Limits { max_splats: 1000, ..Limits::viewer() }).unwrap();
        assert_eq!(splats_of(&thin).len(), 1000);
    }
    if let Some(path) = corpus("biker.spz") {
        let head: Vec<u8> = std::fs::read(&path).unwrap().into_iter().take(4096).collect();
        assert_eq!(sniff(&path, &head), Some(SplatFormat::Spz));
        let scene = load(SplatFormat::Spz, &path, &Limits::viewer()).unwrap();
        assert!(splats_of(&scene).len() > 1000);
        assert!(scene.info.format.contains("version 4"), "{}", scene.info.format);
    }
}

